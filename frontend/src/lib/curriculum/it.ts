export function getLessonBySlug(slug: string): CurriculumLesson | undefined {
  return curriculum.find((l) => l.slug === slug);
}

/** Curriculum phase metadata, keyed by week range — identical arc to the Spanish course. */
export function phaseForWeek(week: number): { number: number; title: string; subtitle: string } {
  if (week <= 4) return { number: 1, title: 'Foundations', subtitle: 'Your first words & sentences' };
  if (week <= 8) return { number: 2, title: 'Building Blocks', subtitle: 'Verbs, questions & real conversations' };
  if (week <= 12) return { number: 3, title: 'The Past & Future', subtitle: 'Tell stories, make plans' };
  if (week <= 16) return { number: 4, title: 'Everyday Life', subtitle: 'Opinions, routines & the real world' };
  if (week <= 20) return { number: 5, title: 'Power Grammar', subtitle: 'The structures of real fluency' };
  return { number: 6, title: 'Fluency', subtitle: 'Sound like you belong' };
}

export function getAllVocab(): VocabItem[] {
  return curriculum.flatMap((l) => l.vocab);
}

export function getVocabById(id: string): VocabItem | undefined {
  return getAllVocab().find((w) => w.id === id);
}

export function getPriorLessons(slug: string): CurriculumLesson[] {
  const idx = curriculum.findIndex((l) => l.slug === slug);
  if (idx <= 0) return [];
  return curriculum.slice(0, idx);
}
