/**
 * The Italian course.
 *
 * Structurally identical to es.ts — same 24 weeks, same six phases, same
 * lesson shape — because the whole app reads a course through one interface
 * (see ./index.ts) and everything from the exercise engine to the sentence
 * builder to the tutor's level ceiling is driven by that shape.
 *
 * A note on the field names. `es` and `exampleEs` are historical: they were
 * named when Spanish was the only course, and they mean "the target language
 * string", not "Spanish". Renaming them to something neutral would touch
 * every exercise component, every test and both courses for no learner-facing
 * benefit, so they stay and this comment stands in for the rename.
 *
 * Every fill-in-the-blank sentence here carries an explicit `wordId`. The
 * Spanish course mostly relies on the engine matching the blank back to a
 * vocabulary entry by substring, which needs a per-language list of articles
 * and pronouns to strip and silently mis-attributes an FSRS result when the
 * guess fails. Being explicit costs one field and removes the whole class of
 * bug — see curriculum-integrity.test.ts.
 */

export interface VocabItem {
  id: string;
  /** The target-language word — Italian here. */
  es: string;
  en: string;
  pron: string;
  exampleEs: string;
  exampleEn: string;
  /** Other English renderings a recall answer should also accept. */
  enAlt?: string[];
}

export interface GrammarSlide {
  title: string;
  body: string;
  examples: Array<{ es: string; en: string }>;
}

export interface ConceptCheck {
  question: string;
  options: string[];
  correct: string;
  explanation: string;
}

export interface DialogueTurn {
  speaker: string;
  es: string;
  en: string;
}

export interface SentenceBuild {
  es: string;
  en: string;
}

export interface CurriculumLesson {
  slug: string;
  title: string;
  subtitle: string;
  week: number;
  order: number;
  theme:
    | 'phonetics'
    | 'verbs'
    | 'family'
    | 'nouns'
    | 'adjectives'
    | 'review'
    | 'grammar'
    | 'conversation';
  emoji: string;
  description: string;
  tip: string;
  vocab: VocabItem[];
  sentences: Array<{ es: string; en: string; blank: string; wordId?: string }>;
  grammar?: GrammarSlide[];
  conceptChecks?: ConceptCheck[];
  dialogue?: DialogueTurn[];
  builds?: SentenceBuild[];
  isReview?: boolean;
}

